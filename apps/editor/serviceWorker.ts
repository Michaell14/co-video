/**
 * The source of `sw.js`: a small service worker that lets the editor open with no network.
 *
 *  - The page itself is network-first (a deploy reaches people at once) with the cached copy as the
 *    offline fallback. Only the editor's own page is ever kept as that copy: a link to some other
 *    file inside the worker's scope must not become what opens offline.
 *  - Code and styles are precached; everything else under `assets/` (fonts) is cached on first use.
 *    Those files carry a hash of their content in their name, so cache-first is always correct, and
 *    a new version of the worker takes over what the one before it holds instead of downloading it
 *    again.
 *  - API calls, WebSockets, range requests and sample media are never touched.
 */
const SOURCE = `// Generated by apps/editor/vite.config.ts. Do not edit.
const CACHE = 'tandem-__VERSION__';
const PRECACHE = __PRECACHE__;
const ON_USE = __ON_USE__;
const scope = self.registration.scope;
const shell = new URL('./', scope).href;

const isPage = (response) => response.ok && /^text\\/html\\b/i.test(response.headers.get('content-type') || '');

// A file under assets/ is the same file wherever a copy of it comes from: the cache of the worker
// this one replaces, or the browser's own cache, which has what the page loaded a moment ago. So a
// deploy costs a returning visitor the files that changed, and a first visit fetches nothing twice.
// The page has no hash in its name and is always asked of the server.
const install = async () => {
  const cache = await caches.open(CACHE);
  const names = (await caches.keys()).filter((name) => name.startsWith('tandem-') && name !== CACHE);
  const earlier = await Promise.all(names.map((name) => caches.open(name)));
  const held = async (url) => {
    for (const other of earlier) {
      const hit = await other.match(url, { ignoreVary: true });
      if (hit) return hit;
    }
    return null;
  };
  const take = async (path, fetched) => {
    const url = new URL(path, scope).href;
    const hit = await held(url);
    if (hit) await cache.put(url, hit);
    else if (fetched) await cache.add(url);
  };
  const page = async () => {
    const response = await fetch(new Request(shell, { cache: 'reload' }));
    if (!isPage(response)) throw new Error('the editor page could not be fetched');
    await cache.put(shell, response);
  };
  await Promise.all([page(), ...PRECACHE.map((path) => take(path, true)), ...ON_USE.map((path) => take(path, false))]);
};

self.addEventListener('install', (event) => {
  event.waitUntil(install().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tandem-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const remember = (key, response) => {
  const copy = response.clone();
  caches.open(CACHE).then((cache) => cache.put(key, copy)).catch(() => {});
  return response;
};

// The editor is one page. The server answers with it for every path below the scope that names no
// file, so those open the editor offline as well. A path that names a file is left to the network,
// and so is the API when the editor is hosted at the root of the server's origin.
const isShell = (path) => path === '' || path === 'index.html';
const opensEditor = (path) => isShell(path) || (!/^(api|ws)(\\/|$)/.test(path) && !path.split('/').pop().includes('.'));

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  if (!request.url.startsWith(scope)) return;
  const path = request.url.slice(scope.length).split(/[?#]/)[0];
  if (request.mode === 'navigate') {
    if (!opensEditor(path)) return;
    event.respondWith(
      fetch(request)
        .then((response) => (isShell(path) && isPage(response) ? remember(shell, response) : response))
        .catch(() => caches.match(shell).then((hit) => hit || Response.error())),
    );
  } else if (path.startsWith('assets/')) {
    event.respondWith(
      caches.match(request).then((hit) => hit || fetch(request).then((response) => (response.ok ? remember(request, response) : response))),
    );
  }
});
`;

export interface ServiceWorkerBuild {
  /** Changes whenever the build's files do; names the worker's cache. */
  version: string;
  /** Files fetched when the worker is installed, as paths relative to its scope. */
  precache: readonly string[];
  /** Files kept once the page has asked for one, and carried from one version to the next. */
  onUse: readonly string[];
}

/** `sw.js` for a build. */
export function serviceWorkerSource(build: ServiceWorkerBuild): string {
  // Replacer functions, because a file name may hold a `$`, which a replacement string would read.
  return SOURCE.replace('__VERSION__', () => build.version)
    .replace('__PRECACHE__', () => JSON.stringify(build.precache))
    .replace('__ON_USE__', () => JSON.stringify(build.onUse));
}

/**
 * Sorts the files of a build (paths relative to the worker's scope) into what the worker fetches
 * when it is installed and what it keeps on first use. Source maps are neither: only developer
 * tools ask for them.
 */
export function serviceWorkerFiles(files: readonly string[]): Pick<ServiceWorkerBuild, 'precache' | 'onUse'> {
  const hashed = files.filter((file) => file.startsWith('assets/') && !file.endsWith('.map')).sort();
  const code = (file: string): boolean => /\.(js|css)$/.test(file);
  return { precache: hashed.filter(code), onUse: hashed.filter((file) => !code(file)) };
}
