/**
 * The source of `sw.js`: a small service worker that lets the editor open with no network.
 *
 *  - The page itself is network-first (a deploy reaches people at once) with the cached copy as the
 *    offline fallback. Only the editor's own page is ever kept as that copy: a link to some other
 *    file inside the worker's scope must not become what opens offline.
 *  - Code and styles are precached; everything else under `assets/` (fonts) is cached on first use.
 *    Those files are content-hashed, so cache-first is always correct, and a new version of the
 *    worker takes over what the one before it holds instead of downloading it again.
 *  - API calls, WebSockets, range requests and sample media are never touched.
 */
const SOURCE = `// Generated by apps/editor/vite.config.ts. Do not edit.
const CACHE = 'tandem-__VERSION__';
const PRECACHE = __PRECACHE__;
const scope = self.registration.scope;
const shell = new URL('./', scope).href;

// A file under assets/ has a hash of its content in its name, so every copy of it is the right
// one: the copy an earlier version of this worker cached, or the one in the browser's own cache
// because the page has just loaded it. Only the page has to be asked of the server.
const precache = async () => {
  const cache = await caches.open(CACHE);
  await Promise.all(
    PRECACHE.map(async (path) => {
      const url = new URL(path, scope).href;
      if (!path.startsWith('assets/')) return cache.add(new Request(url, { cache: 'reload' }));
      const held = await caches.match(url, { ignoreVary: true });
      return held ? cache.put(url, held) : cache.add(url);
    }),
  );
};

self.addEventListener('install', (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tandem-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const remember = (key, response) => {
  if (response.ok) {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(key, copy)).catch(() => {});
  }
  return response;
};

// The editor has one page. The server also answers with it for any path that names no file, so
// those open the editor offline as well; a path with a file name, or one that belongs to the API
// when the editor is hosted at the root of the server's origin, is left to the network.
const isShell = (path) => path === '' || path === 'index.html';
const opensEditor = (path) => isShell(path) || (!/^(api|ws)(\\/|$)/.test(path) && !path.split('/').pop().includes('.'));
const isPage = (response) =>
  response.ok && !response.redirected && /^text\\/html\\b/i.test(response.headers.get('content-type') || '');

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  if (!request.url.startsWith(scope)) return;
  const path = request.url.slice(scope.length).split(/[?#]/)[0];
  if (request.mode === 'navigate') {
    if (!opensEditor(path)) return;
    event.respondWith(
      fetch(request)
        .then((response) => (isShell(path) && isPage(response) ? remember(shell, response) : response))
        .catch(() => caches.match(shell).then((hit) => hit || Response.error())),
    );
  } else if (path.startsWith('assets/')) {
    event.respondWith(caches.match(request).then((hit) => hit || fetch(request).then((response) => remember(request, response))));
  }
});
`;

/** `sw.js` for a build whose precached files (paths relative to the worker's scope) are `precache`. */
export function serviceWorkerSource(version: string, precache: readonly string[]): string {
  return SOURCE.replace('__VERSION__', version).replace('__PRECACHE__', JSON.stringify(precache));
}
