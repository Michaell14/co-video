import { createHash } from 'node:crypto';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

const server = process.env.TANDEM_SERVER ?? 'http://localhost:8787';

/**
 * Emits `sw.js`: a small service worker that lets the editor open with no network.
 *
 *  - The page itself is network-first (a deploy reaches people at once) with the cached copy as the
 *    offline fallback.
 *  - Code and styles are precached; everything else under `assets/` (fonts) is cached on first use.
 *    Those files are content-hashed, so cache-first is always correct.
 *  - API calls, WebSockets, range requests and sample media are never touched.
 */
function serviceWorker(): Plugin {
  return {
    name: 'tandem-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const precache = Object.keys(bundle)
        .filter((f) => /\.(js|css)$/.test(f))
        .sort();
      const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: SW_SOURCE.replace('__VERSION__', version).replace(
          '__PRECACHE__',
          JSON.stringify(['./', ...precache]),
        ),
      });
    },
  };
}

const SW_SOURCE = `// Generated by apps/editor/vite.config.ts. Do not edit.
const CACHE = 'tandem-__VERSION__';
const PRECACHE = __PRECACHE__;
const scope = self.registration.scope;
const shell = new URL('./', scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(new URL(u, scope), { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tandem-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const remember = (key, response) => {
  if (response.ok) {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(key, copy)).catch(() => {});
  }
  return response;
};

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  if (!request.url.startsWith(scope)) return;
  const path = request.url.slice(scope.length).split(/[?#]/)[0];
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => remember(shell, response))
        .catch(() => caches.match(shell).then((hit) => hit || Response.error())),
    );
  } else if (path.startsWith('assets/')) {
    event.respondWith(caches.match(request).then((hit) => hit || fetch(request).then((response) => remember(request, response))));
  }
});
`;

export default defineConfig(({ command }) => ({
  // In production the collaboration server hosts the editor under /app/.
  base: command === 'build' ? (process.env.TANDEM_BASE ?? '/app/') : '/',
  plugins: [react(), serviceWorker()],
  server: {
    port: 5173,
    strictPort: false,
    proxy: {
      '/api': { target: server, changeOrigin: true },
      '/ws': { target: server.replace(/^http/, 'ws'), ws: true },
    },
  },
  build: {
    target: 'es2022',
    sourcemap: true,
    chunkSizeWarningLimit: 1500,
  },
  worker: { format: 'es' },
}));
